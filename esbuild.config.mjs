import { builtinModules } from 'node:module'
import process from 'node:process'

import esbuild from 'esbuild'

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin repository
*/
`

const prod = process.argv[2] === 'production'

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		...builtinModules.map((name) => `node:${name}`),
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	metafile: true,
})

if (prod) {
	const result = await context.rebuild()
	const imports = Object.values(result.metafile.outputs).flatMap((output) => output.imports)
	const unsupported = imports.filter((dependency) => dependency.path !== 'obsidian')

	if (unsupported.length > 0) {
		throw new Error(
			`Mobile bundle has unsupported imports: ${unsupported.map((dependency) => dependency.path).join(', ')}`,
		)
	}

	await context.dispose()
	process.exit(0)
} else {
	await context.watch()
}
